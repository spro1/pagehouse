export type Key = keyof Dict
export const LANGS = { en: { label: 'English', dict: en }, ko: { label: '한국어', dict: ko } } as const
export type Lang = keyof typeof LANGS

function initial(): Lang {
  try {
    const saved = localStorage.getItem('ph:lang')
    if (saved && saved in LANGS) return saved as Lang
  } catch {}
  return 'en'
}

export const lang: Lang = initial()
document.documentElement.lang = lang

export function t(key: Key, vars?: Record<string, string | number>): string {
  let s: string = LANGS[lang].dict[key] ?? en[key] ?? key
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v))
  return s
}

export const hasKey = (key: string): key is Key => key in en

// Every component reads `lang` once at load, so switching reloads the app.
export function setLang(l: Lang) {
  try {
    localStorage.setItem('ph:lang', l)
  } catch {}
  location.reload()
}
